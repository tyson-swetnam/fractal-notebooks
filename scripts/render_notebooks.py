# ------------------------------------------------------------------ text cleaning


def strip_ansi(text: str) -> str:
    return ANSI_RE.sub("", text)


def collapse_carriage_returns(text: str) -> str:
    """Keep only the final state of every '\\r'-rewritten progress line."""
    text = text.replace("\r\n", "\n")
    if "\r" not in text:
        return text
    return "\n".join(line.rsplit("\r", 1)[-1] for line in text.split("\n"))


def scrub_paths(text: str) -> str:
    for pattern, repl in PATH_SCRUBS:
        text = pattern.sub(repl, text)
    return text


def truncate_lines(text: str, max_lines: int) -> str:
    lines = text.split("\n")
    if max_lines and len(lines) > max_lines:
        dropped = len(lines) - max_lines
        lines = lines[:max_lines] + [f"... [{dropped} more lines truncated]"]
    return "\n".join(lines)


def clean_text(text: str, max_lines: int) -> str:
    text = collapse_carriage_returns(strip_ansi(text))
    text = scrub_paths(text)
    text = "\n".join(line.rstrip() for line in text.split("\n"))
    text = truncate_lines(text.strip("\n"), max_lines)
    return text


def one_line(text: str, limit: int = 200) -> str:
    text = scrub_paths(strip_ansi(text or "")).strip()
    first = text.splitlines()[0] if text else ""
    first = first.replace('"', "'").strip()
    return first[:limit] + ("..." if len(first) > limit else "")


