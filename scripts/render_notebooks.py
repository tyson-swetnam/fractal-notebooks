#!/usr/bin/env python3
"""Render the published Jupyter notebooks to committed Markdown pages (OKF v0.2).

Zensical has no mkdocs-jupyter, so every notebook listed in scripts/notebooks.toml
is converted once, with nbconvert's MarkdownExporter and *without execution*, to

    docs/<dir>/<stem>.md          the page (OKF v0.2 frontmatter + banner + body)
    docs/<dir>/<stem>_files/      the extracted images

and both are committed. CI runs ``--check`` to make sure the committed pages are
still what the notebooks produce.

Output policy (SitePreprocessor):
  * widget views (application/vnd.jupyter.widget-view+json) -> italic note;
  * plotly / text/html outputs that also carry a PNG -> the PNG only;
  * script-bearing HTML or plotly JSON without a PNG -> note linking nbviewer;
  * scriptless text/html (tables) kept; text/latex and text/markdown kept;
  * stderr dropped; stdout and text/plain ANSI-stripped, carriage-return
    progress collapsed, machine paths scrubbed, truncated to max_stream_lines;
  * errors keep ename + a one-line evalue, never the traceback;
  * bare function/widget reprs returned by interact() are dropped as noise.

Deterministic by construction: no clock, no git, no network. Dates come from the
manifest (``as_of``); image bytes come from the notebook.

Usage:
  python scripts/render_notebooks.py                 render every manifest entry
  python scripts/render_notebooks.py --check         exit 1 if committed output differs
  python scripts/render_notebooks.py --only dla      render selected stems only
  python scripts/render_notebooks.py --strict        missing/unparseable notebook fails
  python scripts/render_notebooks.py --fail-on-errors   exit 1 if any cell has an error output
  python scripts/render_notebooks.py --clean         delete the generated pages and _files dirs
"""

