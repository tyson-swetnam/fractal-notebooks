@dataclass
class CellStats:
    markdown: int = 0
    code: int = 0
    executed: int = 0
    figures: int = 0
    errors: int = 0
    widgets: int = 0
    interactive: int = 0  # script/plotly outputs replaced by a nbviewer note
    error_names: list[str] = field(default_factory=list)


class SitePreprocessor:
    """Apply the output policy table in place (see module docstring)."""

    def __init__(self, max_stream_lines: int, nbviewer_url: str, code_only: bool = False):
        self.max_stream_lines = max_stream_lines
        self.nbviewer_url = nbviewer_url
        self.code_only = code_only
        self.stats = CellStats()

    # -- helpers -----------------------------------------------------------------
    def _note(self, text: str) -> nbformat.NotebookNode:
        return nbformat.from_dict(
            {"output_type": "display_data", "data": {"text/markdown": text}, "metadata": {}}
        )

    def _interactive_note(self) -> nbformat.NotebookNode:
        self.stats.interactive += 1
        return self._note(
            f"*Interactive figure (Plotly/JavaScript) — [view it on nbviewer]({self.nbviewer_url}).*"
        )

    def _coalesce_streams(self, outputs: list) -> list:
        merged: list = []
        for out in outputs:
            if (
                out.get("output_type") == "stream"
                and merged
                and merged[-1].get("output_type") == "stream"
                and merged[-1].get("name") == out.get("name")
            ):
                merged[-1]["text"] = merged[-1].get("text", "") + out.get("text", "")
            else:
                merged.append(out)
        return merged

    # -- per output --------------------------------------------------------------
    def _process_output(self, out, cell_index: int):
        kind = out.get("output_type")
        if kind == "stream":
            if out.get("name") != "stdout":
                return None
            text = clean_text(out.get("text", ""), self.max_stream_lines)
            if not text:
                return None
            out["text"] = text
            return out
        if kind == "error":
            self.stats.errors += 1
            ename = re.sub(r"[^\w .:-]", "", str(out.get("ename") or "Error")) or "Error"
            self.stats.error_names.append(ename)
            out["ename"] = ename
            out["evalue"] = one_line(out.get("evalue")) or "(no message)"
            out["traceback"] = []
            return out
        if kind not in ("display_data", "execute_result"):
            return None
        data = out.get("data") or {}
        if not data:
            return None
        if WIDGET_MIME in data:
            self.stats.widgets += 1
            return self._note(WIDGET_NOTE)
        has_image = any(m in data for m in IMAGE_MIMES)
        if has_image:
            for mime in ("text/html", PLOTLY_MIME, JS_MIME):
                data.pop(mime, None)
            self.stats.figures += 1
            fig_no = self.stats.figures
            out.setdefault("metadata", {})
            out["metadata"]["alt"] = f"Figure {fig_no}: output of code cell {cell_index}"
            out["data"] = data
            return out
        if "text/html" in data:
            html = data["text/html"]
            if isinstance(html, list):
                html = "".join(html)
            if PLOTLY_MIME in data or SCRIPT_RE.search(html):
                return self._interactive_note()
            data.pop("text/plain", None)  # let the scriptless table win over its repr
            data["text/html"] = html.strip("\n")
            out["data"] = data
            return out
        if PLOTLY_MIME in data or JS_MIME in data:
            if PLOTLY_MIME in data:
                return self._interactive_note()
            return None
        if "text/plain" in data:
            plain = data["text/plain"]
            if isinstance(plain, list):
                plain = "".join(plain)
            if kind == "execute_result" and REPR_NOISE_RE.match(plain.strip()):
                return None
            text = clean_text(plain, self.max_stream_lines)
            if not text and len(data) == 1:
                return None
            data["text/plain"] = text
            out["data"] = data
        return out

    # -- notebook ----------------------------------------------------------------
    def preprocess(self, nb: nbformat.NotebookNode) -> nbformat.NotebookNode:
        for index, cell in enumerate(nb.cells):
            if cell.cell_type == "markdown":
                self.stats.markdown += 1
                continue
            if cell.cell_type != "code":
                continue
            self.stats.code += 1
            outputs = list(cell.get("outputs") or [])
            if cell.get("execution_count") is not None or outputs:
                self.stats.executed += 1
            if self.code_only:
                cell["outputs"] = []
                cell["execution_count"] = None
                continue
            kept = []
            for out in self._coalesce_streams(outputs):
                new = self._process_output(out, index)
                if new is not None:
                    kept.append(new)
            cell["outputs"] = kept
        return nb


