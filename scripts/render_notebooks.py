@dataclass
class Entry:
    src: str
    title: str
    description: str
    tags: list[str]
    as_of: str
    environment: str
    status: str
    author: str
    companion_page: str | None = None
    code_only: bool = False
    heading: str | None = None
    h1_policy: str = "keep"  # keep | replace | demote
    verified_at: str | None = None
    max_stream_lines: int = 120

    @property
    def path(self) -> Path:
        return ROOT / self.src

    @property
    def stem(self) -> str:
        return Path(self.src).stem

    @property
    def out_md(self) -> Path:
        return self.path.with_suffix(".md")

    @property
    def files_dir_name(self) -> str:
        return f"{self.stem}_files"

    @property
    def out_files_dir(self) -> Path:
        return self.path.parent / self.files_dir_name

    @property
    def docs_rel(self) -> str:
        rel = Path(self.src).with_suffix(".md").as_posix()
        if not rel.startswith("docs/"):
            raise ManifestError(f"{self.src}: notebooks must live under docs/")
        return rel[len("docs/"):]


def load_manifest(path: Path = DEFAULT_MANIFEST) -> tuple[dict, list[Entry]]:
    if not path.is_file():
        raise ManifestError(f"manifest not found: {path}")
    with open(path, "rb") as fh:
        data = tomllib.load(fh)
    defaults = data.get("defaults") or {}
    entries: list[Entry] = []
    seen_out: dict[str, str] = {}
    for raw in data.get("notebook") or []:
        missing = [k for k in ("src", "title", "description", "as_of") if not raw.get(k)]
        if missing:
            raise ManifestError(f"[[notebook]] {raw.get('src', '?')}: missing {missing}")
        entry = Entry(
            src=raw["src"],
            title=str(raw["title"]),
            description=" ".join(str(raw["description"]).split()),
            tags=list(raw.get("tags") or defaults.get("tags") or []),
            as_of=str(raw["as_of"]),
            environment=str(raw.get("environment") or defaults.get("environment") or ""),
            status=str(raw.get("status") or defaults.get("status") or "stable"),
            author=str(raw.get("author") or defaults.get("author") or "human:unknown"),
            companion_page=raw.get("companion_page"),
            code_only=bool(raw.get("code_only", False)),
            heading=raw.get("heading"),
            h1_policy=str(raw.get("h1_policy", "keep")),
            verified_at=raw.get("verified_at"),
            max_stream_lines=int(raw.get("max_stream_lines", defaults.get("max_stream_lines", 120))),
        )
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", entry.as_of):
            raise ManifestError(f"{entry.src}: as_of must be YYYY-MM-DD, got {entry.as_of!r}")
        if entry.h1_policy not in ("keep", "replace", "demote"):
            raise ManifestError(f"{entry.src}: h1_policy must be keep|replace|demote")
        if entry.status not in ("draft", "stable", "deprecated"):
            raise ManifestError(f"{entry.src}: status must be draft|stable|deprecated")
        for ch in '"<>':
            if ch in entry.description:
                raise ManifestError(f"{entry.src}: description must not contain {ch!r}")
        if not 50 <= len(entry.description) <= 300:
            raise ManifestError(
                f"{entry.src}: description must be 50-300 characters (is {len(entry.description)})"
            )
        if not entry.src.endswith(".ipynb"):
            raise ManifestError(f"{entry.src}: src must be an .ipynb path")
        out = entry.out_md.as_posix()
        if out in seen_out:
            raise ManifestError(f"{entry.src} and {seen_out[out]} both render to {out}")
        seen_out[out] = entry.src
        entries.append(entry)
    return defaults, entries


# ------------------------------------------------------------------ rendering


def _iter_lines_with_fences(lines: list[str]):
    fence = None
    for line in lines:
        m = FENCE_RE.match(line)
        if m:
            marker = m.group(1)
            if fence is None:
                fence = marker[0] * 3
                yield line, True
                continue
            if marker.startswith(fence):
                fence = None
                yield line, True
                continue
        yield line, fence is not None


# Notebook-to-notebook links. Markdown cells link sibling notebooks as `x.ipynb`; the raw
# notebooks are not published, so point manifest notebooks at their rendered page and
# everything else at the file on GitHub.
KNOWN_NOTEBOOKS: set[str] = set()
IPYNB_LINK_RE = re.compile(r"(\]\()([^)\s#]+?\.ipynb)(#[^)]*)?(\))")


def rewrite_ipynb_links(body: str, entry: "Entry", repo_url: str, branch: str) -> str:
    nb_dir = posixpath.dirname(entry.src)

    def sub(m: re.Match) -> str:
        target = m.group(2)
        if target.startswith(("http://", "https://")):
            return m.group(0)
        resolved = posixpath.normpath(posixpath.join(nb_dir, target))
        frag = m.group(3) or ""
        if resolved in KNOWN_NOTEBOOKS:
            return f"{m.group(1)}{target[:-len('.ipynb')]}.md{frag}{m.group(4)}"
        return f"{m.group(1)}{repo_url.rstrip('/')}/blob/{branch}/{resolved}{frag}{m.group(4)}"

    return IPYNB_LINK_RE.sub(sub, body)


def apply_h1_policy(body: str, heading: str, policy: str) -> str:
    """Leave exactly one H1 in the body, placed first; return the new body."""
    lines = body.split("\n")
    h1_positions = [i for i, (line, in_code) in enumerate(_iter_lines_with_fences(lines)) if not in_code and H1_RE.match(line)]
    if policy == "demote" or not h1_positions:
        for i in h1_positions:
            lines[i] = "#" + lines[i]
        return f"# {heading}\n\n" + "\n".join(lines).lstrip("\n")
    first, *rest = h1_positions
    for i in rest:
        lines[i] = "#" + lines[i]
    if policy == "replace":
        lines[first] = f"# {heading}"
    h1_line = lines.pop(first)
    return f"{h1_line}\n\n" + "\n".join(lines).lstrip("\n")


def tidy_blank_lines(text: str) -> str:
    out: list[str] = []
    blank = 0
    for line, in_code in _iter_lines_with_fences(text.split("\n")):
        if in_code:
            out.append(line)
            blank = 0
            continue
        if line.strip() == "":
            blank += 1
            if blank > 2:
                continue
            out.append("")
        else:
            blank = 0
            out.append(line.rstrip())
    return "\n".join(out).strip("\n") + "\n"


def yaml_str(value: str) -> str:
    """Quote a YAML scalar only when needed (keeps the frontmatter readable)."""
    s = str(value)
    needs = (
        s == ""
        or s.strip() != s
        or s[0] in "!&*?|>'\"%@`#-[]{},"
        or ": " in s
        or " #" in s
        or s.lower() in ("true", "false", "null", "yes", "no", "on", "off", "~")
        or re.fullmatch(r"[-+]?(\d[\d_]*|\d*\.\d+|\d+\.\d*)([eE][-+]?\d+)?", s) is not None
        or re.fullmatch(r"\d{4}-\d{2}-\d{2}.*", s) is not None
        or "\n" in s
    )
    if not needs:
        return s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def iso_date(day: str) -> str:
    return f"{day}T00:00:00Z"


def build_frontmatter(entry: Entry, nb_meta: dict, stats: CellStats, urls: dict) -> str:
    desc = entry.description
    lines = ["---", f"type: {OKF_TYPE}", f"title: {yaml_str(entry.title)}"]
    if len(desc) > 80:
        lines.append("description: >-")
        lines.extend(_wrap(desc, 78, "  "))
    else:
        lines.append(f"description: {yaml_str(desc)}")
    lines.append(f"resource: {urls['page']}")
    lines.append("tags: [" + ", ".join(entry.tags) + "]")
    if entry.companion_page:
        lines.append(f"companion_page: {urls['companion']}")
    kernel = (nb_meta.get("kernelspec") or {}).get("display_name") or (nb_meta.get("kernelspec") or {}).get("name") or "unknown"
    if entry.code_only:
        outputs_mode = "none (code-only page; the notebook needs a live service to run)"
    elif stats.figures == 0 and stats.widgets > 0:
        outputs_mode = "stored (widget views only; no static figures)"
    elif stats.executed == 0:
        outputs_mode = "none (notebook stored without outputs)"
    else:
        outputs_mode = "stored"
    lines += [
        "notebook:",
        f"  source: {urls['blob']}",
        f"  raw: {urls['raw']}",
        f"  nbviewer: {urls['nbviewer']}",
        f"  colab: {urls['colab']}",
        f"  kernel: {yaml_str(kernel)}",
        f"  environment: {yaml_str(entry.environment)}",
        "  cells:",
        f"    markdown: {stats.markdown}",
        f"    code: {stats.code}",
        f"    executed: {stats.executed}",
        f"    figures: {stats.figures}",
        f"    errors: {stats.errors}",
        f"  outputs: {yaml_str(outputs_mode)}",
        "sources:",
        "  - id: ipynb",
        f"    resource: {urls['blob']}",
        f"    title: {yaml_str(Path(entry.src).name)}",
        f'    last_modified: "{iso_date(entry.as_of)}"',
        "generated:",
        f"  by: {GENERATOR}",
        f'  at: "{iso_date(entry.as_of)}"',
    ]
    if entry.verified_at:
        lines += ["verified:", f"  - by: {entry.author}", f'    at: "{iso_date(str(entry.verified_at))}"']
    lines.append(f"status: {entry.status}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def _wrap(text: str, width: int, indent: str) -> list[str]:
    words = text.split()
    out: list[str] = []
    cur = ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            out.append(indent + cur)
            cur = w
        else:
            cur = f"{cur} {w}" if cur else w
    if cur:
        out.append(indent + cur)
    return out


def build_banner(entry: Entry, stats: CellStats, urls: dict, kernel: str) -> str:
    name = Path(entry.src).name
    if entry.code_only:
        state = (
            f"This page shows the code of `{name}` without outputs: the notebook needs a running "
            "service to execute and is not run at build time."
        )
    elif stats.executed == 0:
        state = f"This page was rendered from `{name}`, which is stored without outputs; it is not executed at build time."
    else:
        state = (
            f"This page was rendered from the stored outputs of `{name}` as of {entry.as_of}; "
            "it is not executed at build time."
        )
    extras = []
    def plural(n: int, noun: str, verb_s: str, verb_p: str) -> str:
        return f"{n} {noun}{'' if n == 1 else 's'} {verb_s if n == 1 else verb_p}"

    if stats.widgets:
        extras.append(plural(stats.widgets, "interactive widget output", "needs", "need") + " a live kernel and is shown as a note" if stats.widgets == 1 else plural(stats.widgets, "interactive widget output", "needs", "need") + " a live kernel and are shown as notes")
    if stats.interactive:
        extras.append(plural(stats.interactive, "Plotly/JavaScript figure", "is", "are") + " linked to nbviewer")
    if stats.errors:
        extras.append(plural(stats.errors, "cell", "raised", "raised") + f" an error when the notebook was last run ({', '.join(sorted(set(stats.error_names)))})")
    if extras:
        state += " " + "; ".join(extras) + "."
    links = (
        f"[View on GitHub]({urls['blob']}) · [Open in nbviewer]({urls['nbviewer']}) · "
        f"[Open in Colab]({urls['colab']}) · [Raw .ipynb]({urls['raw']})"
    )
    env = f"Kernel: {kernel}" + (f" · Environment: {entry.environment}" if entry.environment else "")
    if entry.companion_page:
        env += f" · Companion page: [{entry.companion_page}]({urls['companion']})"
    return (
        '!!! info "Jupyter notebook"\n\n'
        f"    {state}\n\n"
        f"    {links}\n\n"
        f"    {env}\n"
    )


def make_exporter() -> MarkdownExporter:
    c = Config()
    c.TemplateExporter.extra_template_basedirs = [str(TEMPLATES)]
    c.TemplateExporter.template_name = TEMPLATE_NAME
    c.NbConvertBase.display_data_priority = list(DISPLAY_DATA_PRIORITY)
    c.ExtractOutputPreprocessor.enabled = True
    c.ExtractOutputPreprocessor.output_filename_template = "{unique_key}_{cell_index}_{index}{extension}"
    c.RegexRemovePreprocessor.enabled = True
    c.RegexRemovePreprocessor.patterns = [r"\s*\Z"]
    c.ExtractAttachmentsPreprocessor.enabled = True
    return MarkdownExporter(config=c)


@dataclass
class Rendered:
    entry: Entry
    markdown: str
    files: dict[str, bytes]  # path relative to the page's directory -> bytes
    stats: CellStats


def repo_urls(entry: Entry, site_url: str, repo_url: str, branch: str) -> dict:
    repo = repo_url.rstrip("/")
    owner_repo = repo.split("github.com/", 1)[-1]
    src = entry.src
    urls = {
        "page": html_url(site_url, entry.docs_rel),
        "blob": f"{repo}/blob/{branch}/{src}",
        "raw": f"https://raw.githubusercontent.com/{owner_repo}/{branch}/{src}",
        "nbviewer": f"https://nbviewer.org/github/{owner_repo}/blob/{branch}/{src}",
        "colab": f"https://colab.research.google.com/github/{owner_repo}/blob/{branch}/{src}",
    }
    if entry.companion_page:
        cp = entry.companion_page
        urls["companion"] = cp if cp.startswith("http") else site_url.rstrip("/") + "/" + cp.lstrip("/")
    return urls


def render_entry(entry: Entry, site_url: str, repo_url: str, branch: str, exporter: MarkdownExporter | None = None) -> Rendered:
    exporter = exporter or make_exporter()
    nb = nbformat.read(entry.path, as_version=4)
    urls = repo_urls(entry, site_url, repo_url, branch)
    pre = SitePreprocessor(entry.max_stream_lines, urls["nbviewer"], code_only=entry.code_only)
    nb = pre.preprocess(copy.deepcopy(nb))
    resources = {"unique_key": entry.stem, "output_files_dir": entry.files_dir_name, "default_language": "python"}
    body, resources = exporter.from_notebook_node(nb, resources=resources)
    files = {k.replace(os.sep, "/"): v for k, v in (resources.get("outputs") or {}).items()}
    heading = entry.heading or entry.title
    body = apply_h1_policy(body, heading, entry.h1_policy)
    body = rewrite_ipynb_links(body, entry, repo_url, branch)
    kernel = (nb.metadata.get("kernelspec") or {}).get("display_name") or "unknown"
    banner = build_banner(entry, pre.stats, urls, kernel)
    h1, _, rest = body.partition("\n")
    body = f"{h1}\n\n{banner}\n{rest.lstrip(chr(10))}"
    text = build_frontmatter(entry, nb.metadata, pre.stats, urls) + "\n" + MARKER + "\n\n" + tidy_blank_lines(body)
    return Rendered(entry, text, files, pre.stats)


# ------------------------------------------------------------------ disk


def is_generated_page(path: Path) -> bool:
    try:
        head = path.read_text(encoding="utf-8")[:4000]
    except (OSError, UnicodeDecodeError):
        return False
    return GENERATOR in head and MARKER.split(".")[0] in head


def diff_summary(rendered: Rendered) -> list[str]:
    """Human-readable list of differences between the rendered result and disk."""
    problems: list[str] = []
    md = rendered.entry.out_md
    if not md.exists():
        problems.append(f"{md.relative_to(ROOT)}: missing")
    elif md.read_bytes() != rendered.markdown.encode("utf-8"):
        problems.append(f"{md.relative_to(ROOT)}: content differs")
    fdir = rendered.entry.out_files_dir
    on_disk = {p.relative_to(fdir.parent).as_posix(): p for p in fdir.rglob("*") if p.is_file()} if fdir.exists() else {}
    for rel, data in rendered.files.items():
        p = on_disk.pop(rel, None)
        if p is None:
            problems.append(f"{fdir.parent.relative_to(ROOT)}/{rel}: missing")
        elif p.read_bytes() != data:
            problems.append(f"{fdir.parent.relative_to(ROOT)}/{rel}: content differs")
    for rel in sorted(on_disk):
        problems.append(f"{fdir.parent.relative_to(ROOT)}/{rel}: stale (not produced any more)")
    return problems


def write_rendered(rendered: Rendered, strict: bool) -> tuple[bool, int]:
    """Write page + files. Returns (page_changed, files_written)."""
    entry = rendered.entry
    md = entry.out_md
    if md.exists() and not is_generated_page(md):
        msg = f"refusing to overwrite {md.relative_to(ROOT)}: it was not generated by this script"
        if strict:
            raise RuntimeError(msg)
        print(f"ERROR {msg}", file=sys.stderr)
        return False, 0
    new_bytes = rendered.markdown.encode("utf-8")
    changed = not md.exists() or md.read_bytes() != new_bytes
    if changed:
        md.write_bytes(new_bytes)
    fdir = entry.out_files_dir
    written = 0
    wanted = {rel for rel in rendered.files if rel.startswith(entry.files_dir_name + "/")}
    if fdir.exists():
        for p in fdir.rglob("*"):
            if p.is_file() and p.relative_to(fdir.parent).as_posix() not in wanted:
                p.unlink()
    for rel, data in rendered.files.items():
        target = fdir.parent / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_bytes() != data:
            target.write_bytes(data)
            written += 1
    if fdir.exists() and not any(fdir.iterdir()):
        fdir.rmdir()
    return changed, written


def clean_entry(entry: Entry) -> list[str]:
    removed = []
    if entry.out_md.exists():
        if not is_generated_page(entry.out_md):
            print(f"skip {entry.out_md.relative_to(ROOT)}: not generated by this script", file=sys.stderr)
        else:
            entry.out_md.unlink()
            removed.append(entry.out_md.relative_to(ROOT).as_posix())
    if entry.out_files_dir.exists():
        shutil.rmtree(entry.out_files_dir)
        removed.append(entry.out_files_dir.relative_to(ROOT).as_posix() + "/")
    return removed


# ------------------------------------------------------------------ main


def resolve_site(defaults: dict, config_path: str | None) -> tuple[str, str, str]:
    """site_url, repo_url, branch — from zensical.toml when available, else the manifest."""
    branch = str(defaults.get("branch", "main"))
    if config_path is not None or (ROOT / "zensical.toml").is_file():
        cfg = load_config(ROOT, config_path)  # raises ConfigError if --config points nowhere
        site = str(cfg.get("site_url") or defaults.get("site_url") or "").rstrip("/")
        repo = str(cfg.get("repo_url") or defaults.get("repo_url") or "").rstrip("/")
    else:
        site = str(defaults.get("site_url") or "").rstrip("/")
        repo = str(defaults.get("repo_url") or "").rstrip("/")
    if not site or not repo:
        raise ManifestError("site_url and repo_url must be set in zensical.toml [project] or in notebooks.toml [defaults]")
    return site, repo, branch


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(DEFAULT_MANIFEST), help="scripts/notebooks.toml")
    ap.add_argument("--config", default=None, help="zensical.toml for site_url/repo_url (default: repo root if present, else manifest [defaults])")
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed output differs; writes nothing")
    ap.add_argument("--only", action="append", default=[], metavar="STEM", help="render only these stems (repeatable)")
    ap.add_argument("--strict", action="store_true", help="a missing or unparseable notebook fails the run")
    ap.add_argument("--fail-on-errors", action="store_true", help="exit 1 if any rendered notebook has error outputs")
    ap.add_argument("--clean", action="store_true", help="delete the generated pages and _files dirs, then exit")
    ap.add_argument("-q", "--quiet", action="store_true")
    args = ap.parse_args(argv)

    try:
        defaults, entries = load_manifest(Path(args.manifest))
        KNOWN_NOTEBOOKS.update(e.src for e in entries)
        site_url, repo_url, branch = resolve_site(defaults, args.config)
    except (ManifestError, ConfigError) as e:
        print(f"ERROR {e}", file=sys.stderr)
        return 2

    if args.only:
        wanted = set(args.only)
        entries = [e for e in entries if e.stem in wanted or e.src in wanted]
        unknown = wanted - {e.stem for e in entries} - {e.src for e in entries}
        if unknown:
            print(f"ERROR --only: unknown notebooks {sorted(unknown)}", file=sys.stderr)
            return 2

    if args.clean:
        for e in entries:
            for rel in clean_entry(e):
                print(f"removed {rel}")
        return 0

    exporter = make_exporter()
    failures = 0
    drift: list[str] = []
    n_images = n_err_nbs = n_changed = 0
    for entry in entries:
        if not entry.path.is_file():
            msg = f"{entry.src}: notebook not found"
            print(("ERROR " if args.strict else "WARN  ") + msg, file=sys.stderr)
            failures += args.strict
            continue
        try:
            rendered = render_entry(entry, site_url, repo_url, branch, exporter)
        except Exception as e:  # noqa: BLE001 - report and continue unless strict
            msg = f"{entry.src}: render failed: {type(e).__name__}: {e}"
            print(("ERROR " if args.strict else "WARN  ") + msg, file=sys.stderr)
            failures += 1 if args.strict else 0
            continue
        n_images += len(rendered.files)
        n_err_nbs += 1 if rendered.stats.errors else 0
        if args.check:
            problems = diff_summary(rendered)
            drift.extend(problems)
            status = "DRIFT" if problems else "ok   "
        else:
            try:
                changed, written = write_rendered(rendered, args.strict)
            except RuntimeError as e:
                print(f"ERROR {e}", file=sys.stderr)
                failures += 1
                continue
            n_changed += int(changed)
            status = "wrote" if changed or written else "fresh"
        if not args.quiet:
            s = rendered.stats
            print(
                f"{status} {entry.out_md.relative_to(ROOT)}  "
                f"({len(rendered.files)} images, {s.code} code cells, {s.executed} executed, "
                f"{s.errors} errors, {s.widgets} widgets, {s.interactive} interactive)"
            )
    if args.check and drift:
        for line in drift:
            print(f"DRIFT {line}", file=sys.stderr)
        print(f"render_notebooks --check: {len(drift)} difference(s); run `python scripts/render_notebooks.py` and commit.", file=sys.stderr)
        return 1
    print(
        f"render_notebooks: {len(entries)} notebooks, {n_images} images, "
        f"{n_err_nbs} notebook(s) with error outputs" + ("" if args.check else f", {n_changed} page(s) changed")
    )
    if failures:
        return 1
    if args.fail_on_errors and n_err_nbs:
        print("render_notebooks: --fail-on-errors set and error outputs are present", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
